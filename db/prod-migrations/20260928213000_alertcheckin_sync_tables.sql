-- AlertCheckin nightly sync: site mapping (AlertCheckin site name -> unit), run log and review list.
create table if not exists public.alertcheckin_site_map (
  ac_site_name text primary key,
  unit_id uuid not null references public.units(id) on delete cascade,
  created_at timestamptz not null default now()
);
create table if not exists public.alertcheckin_sync_runs (
  id uuid primary key default gen_random_uuid(),
  sync_date date not null,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  rows_read int default 0, inserted int default 0, skipped int default 0, unmatched int default 0,
  error text
);
create table if not exists public.alertcheckin_unmatched (
  id uuid primary key default gen_random_uuid(),
  sync_date date not null,
  ac_site_name text not null,
  staff_name text not null,
  unit_id uuid,
  reason text not null,
  hours numeric,
  created_at timestamptz not null default now(),
  unique (sync_date, ac_site_name, staff_name)
);
grant select on public.alertcheckin_site_map, public.alertcheckin_sync_runs, public.alertcheckin_unmatched to authenticated;
grant all on public.alertcheckin_site_map, public.alertcheckin_sync_runs, public.alertcheckin_unmatched to service_role;
alter table public.alertcheckin_site_map enable row level security;
alter table public.alertcheckin_sync_runs enable row level security;
alter table public.alertcheckin_unmatched enable row level security;
create policy "Admins read ac site map" on public.alertcheckin_site_map for select to authenticated using ((select public.is_admin_user()));
create policy "Admins read ac runs" on public.alertcheckin_sync_runs for select to authenticated using ((select public.is_admin_user()));
create policy "Admins read ac unmatched" on public.alertcheckin_unmatched for select to authenticated using ((select public.is_admin_user()));
